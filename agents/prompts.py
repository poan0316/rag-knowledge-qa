"""多智能体报告生成：角色提示词 + 图状态定义。"""
from typing import List, TypedDict


class AgentState(TypedDict):
    """LangGraph 工作流的状态。"""
    topic: str            # 报告主题
    research_brief: str   # 研究员产出的研究简报（带 [来源 N] 标注）
    sources: List[str]    # 检索到的来源文件名（按 [来源 N] 顺序）
    draft: str            # 写手产出的报告初稿/修改稿
    feedback: str         # 审校意见
    verdict: str          # 审校结论：通过 / 需修改
    iteration: int        # 已重写次数
    final_report: str     # 定稿报告


